-- Esquema físico del sistema académico Inudi Perú. Migración inicial H2.
create table accounts (
 id bigint generated by default as identity primary key,
 version bigint not null default 0,
 full_name varchar(120) not null,
 email varchar(180) not null,
 password varchar(100) not null,
 role varchar(30) not null,
 active boolean not null,
 professional_title varchar(180),
 phone varchar(30),
 unique(email)
);
create table courses (
 id bigint generated by default as identity primary key,
 version bigint not null default 0,
 title varchar(180) not null,
 description varchar(6000) not null,
 objectives varchar(2000) not null,
 category varchar(100) not null,
 level varchar(50) not null,
 duration_hours integer not null,
 price numeric(10,2) not null,
 published boolean not null,
 certificate_enabled boolean not null
);
create table learning_modules (
 id bigint generated by default as identity primary key,
 version bigint not null default 0,
 course_id bigint not null references courses(id),
 title varchar(180) not null,
 position integer not null
);
create table contents (
 id bigint generated by default as identity primary key,
 version bigint not null default 0,
 module_id bigint not null references learning_modules(id),
 title varchar(180) not null,
 type varchar(30) not null,
 body varchar(12000) not null,
 resource_url varchar(1000),
 file_key varchar(100),
 file_name varchar(200),
 preview boolean not null,
 position integer not null,
 max_attempts integer not null,
 pass_percent integer not null
);
create table enrollments (
 id bigint generated by default as identity primary key,
 version bigint not null default 0,
 student_id bigint not null references accounts(id),
 course_id bigint not null references courses(id),
 starts_at timestamp(6) not null,
 expires_at timestamp(6) not null,
 status varchar(30) not null,
 unique(student_id,course_id)
);
create table payments (
 id bigint generated by default as identity primary key,
 version bigint not null default 0,
 student_id bigint not null references accounts(id),
 course_id bigint not null references courses(id),
 amount numeric(10,2) not null,
 status varchar(30) not null,
 reference varchar(120) not null,
 created_at timestamp(6) not null,
 confirmed_at timestamp(6)
);
create table cart_items (
 id bigint generated by default as identity primary key,
 version bigint not null default 0,
 student_id bigint not null references accounts(id),
 course_id bigint not null references courses(id),
 unique(student_id,course_id)
);
create table progress (
 id bigint generated by default as identity primary key,
 version bigint not null default 0,
 student_id bigint not null references accounts(id),
 content_id bigint not null references contents(id),
 completed_at timestamp(6) not null,
 unique(student_id,content_id)
);
create table submissions (
 id bigint generated by default as identity primary key,
 version bigint not null default 0,
 student_id bigint not null references accounts(id),
 content_id bigint not null references contents(id),
 attempt_number integer not null,
 file_key varchar(100) not null,
 file_name varchar(200) not null,
 comment varchar(1000) not null,
 grade numeric(10,2),
 feedback varchar(1000),
 created_at timestamp(6) not null,
 unique(student_id,content_id,attempt_number)
);
create table questions (
 id bigint generated by default as identity primary key,
 version bigint not null default 0,
 content_id bigint not null references contents(id),
 type varchar(30) not null,
 prompt varchar(2000) not null,
 options_text varchar(3000) not null,
 correct_answer varchar(2000) not null,
 explanation varchar(2000) not null,
 points integer not null,
 position integer not null
);
create table exam_attempts (
 id bigint generated by default as identity primary key,
 version bigint not null default 0,
 student_id bigint not null references accounts(id),
 content_id bigint not null references contents(id),
 attempt_number integer not null,
 percent numeric(10,2) not null,
 stars integer not null,
 passed boolean not null,
 created_at timestamp(6) not null,
 unique(student_id,content_id,attempt_number)
);
create table exam_answers (
 id bigint generated by default as identity primary key,
 version bigint not null default 0,
 attempt_id bigint not null references exam_attempts(id),
 question_id bigint not null references questions(id),
 answer_text varchar(3000) not null,
 correct boolean not null,
 earned_points integer not null,
 unique(attempt_id,question_id)
);
create table discussions (
 id bigint generated by default as identity primary key,
 version bigint not null default 0,
 content_id bigint not null references contents(id),
 author_id bigint not null references accounts(id),
 parent_id bigint references discussions(id),
 body varchar(4000) not null,
 deleted boolean not null,
 created_at timestamp(6) not null
);
create table reactions (
 id bigint generated by default as identity primary key,
 version bigint not null default 0,
 post_id bigint not null references discussions(id),
 actor_id bigint not null references accounts(id),
 type varchar(30) not null,
 unique(post_id,actor_id)
);
create table ratings (
 id bigint generated by default as identity primary key,
 version bigint not null default 0,
 post_id bigint not null references discussions(id),
 actor_id bigint not null references accounts(id),
 score integer not null,
 unique(post_id,actor_id)
);
create table course_reviews (
 id bigint generated by default as identity primary key,
 version bigint not null default 0,
 course_id bigint not null references courses(id),
 author_id bigint not null references accounts(id),
 body varchar(2000) not null,
 score integer not null,
 created_at timestamp(6) not null,
 unique(course_id,author_id)
);
create table certificates (
 id bigint generated by default as identity primary key,
 version bigint not null default 0,
 student_id bigint not null references accounts(id),
 course_id bigint not null references courses(id),
 code varchar(7) not null,
 student_name varchar(120) not null,
 course_title varchar(180) not null,
 issued_at timestamp(6) not null,
 unique(student_id,course_id),
 unique(code)
);
create table audit_entries (
 id bigint generated by default as identity primary key,
 version bigint not null default 0,
 actor_id bigint not null references accounts(id),
 action varchar(80) not null,
 details varchar(1000) not null,
 created_at timestamp(6) not null
);
create table course_teachers (course_id bigint not null references courses(id), teacher_id bigint not null references accounts(id), primary key(course_id,teacher_id));
create index ix_contents_module on contents(module_id,position);
create index ix_enrollments_course on enrollments(course_id,status);
create index ix_progress_student on progress(student_id);
create index ix_submissions_content on submissions(content_id,created_at);
create index ix_discussions_content on discussions(content_id,created_at);
create index ix_payments_status on payments(status,created_at);
